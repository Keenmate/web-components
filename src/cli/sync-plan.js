/**
 * The sync plan: what every devkit-owned file in a component SHOULD contain.
 * `kmwc sync` writes it, `kmwc sync --check` and `kmwc doctor` diff against it
 * — one computation, so "what sync would do" and "what doctor complains about"
 * can never disagree.
 */
import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { DEVKIT_ROOT } from '../config.js';
import { renderTemplate } from '../template.js';

export { renderTemplate };

export const GENERATED_MARK = 'GENERATED by `kmwc sync`';

const GENERATED_HEADER =
  `# ${GENERATED_MARK} from @keenmate/web-components-devkit — do not edit.\n` +
  `# Change package.json#kmwc (or the devkit template) and re-run \`npx kmwc sync\`.`;

export const CLAUDE_BLOCK_START = '<!-- kmwc:devkit:start — managed by `kmwc sync`, do not edit inside -->';
export const CLAUDE_BLOCK_END = '<!-- kmwc:devkit:end -->';

/** Files rendered wholesale from templates. */
export const GENERATED_FILES = [
  { path: 'Dockerfile', template: 'Dockerfile.tmpl' },
  { path: 'nginx.conf', template: 'nginx.conf.tmpl' },
  { path: 'Makefile', template: 'Makefile.tmpl' },
  { path: '.dockerignore', template: 'dockerignore.tmpl' },
];

const PLAYWRIGHT_CONFIG_FILES = ['playwright.config.ts', 'playwright.config.js', 'playwright.config.mjs'];
const CEM_CONFIG_FILE = 'custom-elements-manifest.config.mjs';

export function getTemplate(templateName) {
  return readFileSync(join(DEVKIT_ROOT, 'templates', templateName), 'utf8');
}

export function getTemplateVariables(config) {
  return {
    HEADER: GENERATED_HEADER,
    ID: config.id,
    PACKAGE_NAME: config.packageName,
    NODE_IMAGE: config.image.nodeImage,
    INSTALL_COMMAND: config.image.installCommand,
    COPY_PACKAGE_JSONS: config.image.packageJsonPaths
      .map((packageJsonPath) => {
        const targetDirectory = packageJsonPath.includes('/') ? packageJsonPath.slice(0, packageJsonPath.lastIndexOf('/') + 1) : './';
        return `COPY ${packageJsonPath} ${targetDirectory}`;
      })
      .join('\n'),
    OUT_DIR: config.examples.outDir,
    RUNNER: config.image.runner,
    IMAGE_NAME: config.image.name,
    CONTAINER_NAME: config.image.container,
    IMAGE_PORT: config.ports.image,
    DEV_PORT: config.ports.dev,
    PREVIEW_PORT: config.ports.dev + 1,
  };
}

/** A `node -e` one-liner that removes the given paths (works in npm scripts on every OS). */
function generateRemoveCommand(paths) {
  return `node -e "for (const p of ${JSON.stringify(paths).replace(/"/g, "'")}) require('fs').rmSync(p,{recursive:true,force:true})"`;
}

const hasAnyFile = (root, fileNames) => fileNames.some((fileName) => existsSync(join(root, fileName)));

/** Scripts every component should expose (only added when missing). */
export function getStandardScripts(config) {
  const scripts = {
    dev: 'vite',
    build: 'vite build',
    'build:examples': 'vite build --mode examples',
    'preview:examples': 'vite preview --mode examples',
    'clean:dist': generateRemoveCommand(['dist']),
    clean: generateRemoveCommand(['dist', config.examples.outDir]),
    doctor: 'kmwc doctor',
  };
  if (existsSync(join(config.root, config.cssVariables.manifest))) scripts['check:vars'] = 'kmwc check-vars';
  if (existsSync(join(config.root, CEM_CONFIG_FILE))) scripts.analyze = 'cem analyze';
  if (hasAnyFile(config.root, PLAYWRIGHT_CONFIG_FILES)) {
    Object.assign(scripts, {
      'test:e2e': 'playwright test',
      'test:e2e:ui': 'playwright test --ui',
      'test:e2e:headed': 'playwright test --headed',
      'test:e2e:install': 'playwright install chromium',
    });
  }
  return scripts;
}

/** Insert or replace the managed block in a CLAUDE.md body (creates the file body when absent). */
export function updateClaudeBlock(claudeMdText) {
  const block = `${CLAUDE_BLOCK_START}\n${getTemplate('claude-block.md').trim()}\n${CLAUDE_BLOCK_END}`;
  if (claudeMdText == null) return `# CLAUDE.md\n\n${block}\n`;
  const startIndex = claudeMdText.indexOf(CLAUDE_BLOCK_START);
  const endIndex = claudeMdText.indexOf(CLAUDE_BLOCK_END);
  if (startIndex !== -1 && endIndex > startIndex) {
    return claudeMdText.slice(0, startIndex) + block + claudeMdText.slice(endIndex + CLAUDE_BLOCK_END.length);
  }
  // No block yet: place it right after the first H1 (or at the top).
  const firstHeading = claudeMdText.match(/^# .*$/m);
  if (!firstHeading) return `${block}\n\n${claudeMdText}`;
  const insertIndex = firstHeading.index + firstHeading[0].length;
  return `${claudeMdText.slice(0, insertIndex)}\n\n${block}\n${claudeMdText.slice(insertIndex)}`;
}

function getFileTextOrNull(filePath) {
  return existsSync(filePath) ? readFileSync(filePath, 'utf8') : null;
}

/** Normalize line endings so a CRLF checkout doesn't read as drift. */
const normalizeLineEndings = (text) => (text == null ? text : text.replace(/\r\n/g, '\n'));

/**
 * @returns {Array<{ path: string, kind: 'generated'|'claude'|'gitignore', expectedText: string, currentText: string|null, isChanged: boolean }>}
 */
export function getSyncPlan(config) {
  const variables = getTemplateVariables(config);
  const skippedFiles = new Set(config.sync.skippedFiles);
  const planItems = [];

  for (const generatedFile of GENERATED_FILES) {
    if (skippedFiles.has(generatedFile.path)) continue;
    const expectedText = renderTemplate(getTemplate(generatedFile.template), variables);
    const currentText = normalizeLineEndings(getFileTextOrNull(join(config.root, generatedFile.path)));
    planItems.push({ path: generatedFile.path, kind: 'generated', expectedText, currentText, isChanged: currentText !== expectedText });
  }

  if (!skippedFiles.has('CLAUDE.md')) {
    const currentText = normalizeLineEndings(getFileTextOrNull(join(config.root, 'CLAUDE.md')));
    const expectedText = updateClaudeBlock(currentText);
    planItems.push({ path: 'CLAUDE.md', kind: 'claude', expectedText, currentText, isChanged: currentText !== expectedText });
  }

  if (!skippedFiles.has('.gitignore')) {
    const currentText = normalizeLineEndings(getFileTextOrNull(join(config.root, '.gitignore')));
    const currentLines = (currentText || '').split('\n').map((line) => line.trim());
    const wantedLines = [`${config.examples.outDir}/`, '.makefile.env'];
    const missingLines = wantedLines.filter((line) => !currentLines.includes(line) && !currentLines.includes(line.replace(/\/$/, '')));
    const expectedText = missingLines.length
      ? (currentText ? currentText.replace(/\n?$/, '\n') : '') + `# kmwc\n${missingLines.join('\n')}\n`
      : currentText;
    planItems.push({ path: '.gitignore', kind: 'gitignore', expectedText, currentText, isChanged: missingLines.length > 0 });
  }

  return planItems;
}

/** Missing and differing standard scripts. */
export function getScriptsPlan(config) {
  const currentScripts = config.packageJson.scripts || {};
  const standardScripts = getStandardScripts(config);
  const missingScripts = {};
  const differingScripts = {};
  for (const [scriptName, command] of Object.entries(standardScripts)) {
    if (!(scriptName in currentScripts)) missingScripts[scriptName] = command;
    else if (['dev', 'build:examples', 'preview:examples'].includes(scriptName) && currentScripts[scriptName] !== command) {
      differingScripts[scriptName] = { currentCommand: currentScripts[scriptName], standardCommand: command };
    }
  }
  return { missingScripts, differingScripts };
}
